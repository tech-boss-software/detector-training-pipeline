"""One command: synthesise (or validate) a dataset, train, evaluate, export to ONNX, infer and write the model card."""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import evaluate
import export
import infer
import model_card
import synthetic
import train


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="artifacts")
    parser.add_argument("--data", default=None, help="YOLO-layout dataset; omitted = generate the synthetic set")
    parser.add_argument("--count", type=int, default=200, help="synthetic image count")
    parser.add_argument("--epochs", type=int, default=8)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--threads", type=int, default=4)
    parser.add_argument("--cache-dir", default=None)
    parser.add_argument("--threshold", type=float, default=0.5)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--image-size", type=int, default=320, help="shorter side after the internal resize; raise for small objects")
    args = parser.parse_args(argv)

    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    timings, commands = {}, []

    def step(name, function, command):
        started = time.perf_counter()
        result = function()
        timings[name] = time.perf_counter() - started
        commands.append(command)
        print(f"[{name}] {timings[name]:.1f} s")
        return result

    if args.data:
        data = Path(args.data)
        origin = f"operator-supplied dataset at {data}"
    else:
        data = output / "dataset"
        step("synthetic", lambda: synthetic.generate(data, args.count, seed=7), f"python synthetic.py --output {data} --count {args.count} --seed 7")
        origin = f"synthetic shapes generated by synthetic.py (seed 7, {args.count} images)"
    common = ["--data", str(data), "--threads", str(args.threads)] + (["--cache-dir", args.cache_dir] if args.cache_dir else [])
    train_args = common + ["--output", str(output), "--epochs", str(args.epochs), "--seed", str(args.seed), "--device", args.device,
                           "--origin", origin, "--image-size", str(args.image_size)]
    if args.limit:
        train_args += ["--limit", str(args.limit)]
    step("train", lambda: train.main(train_args), "python train.py " + " ".join(train_args))
    eval_args = common + ["--artifacts", str(output), "--threshold", str(args.threshold), "--device", args.device]
    step("evaluate", lambda: evaluate.main(eval_args), "python evaluate.py " + " ".join(eval_args))
    export_args = common + ["--artifacts", str(output)]
    step("export", lambda: export.main(export_args), "python export.py " + " ".join(export_args))
    splits = json.loads((output / "training_log.json").read_text(encoding="utf-8"))["split"]
    samples = [str(data / "images" / name) for name in splits["test"][:3]]
    infer_args = ["--model", str(output / "model.onnx"), "--input", *samples, "--output", str(output / "inference"),
                  "--threshold", str(args.threshold), "--threads", str(args.threads)]
    step("infer", lambda: infer.main(infer_args), "python infer.py " + " ".join(infer_args))
    card_args = ["--artifacts", str(output), "--output", str(output / "MODEL_CARD.md")]
    step("model_card", lambda: model_card.main(card_args), "python model_card.py " + " ".join(card_args))
    summary = {"timings_seconds": timings, "commands": commands, "total_seconds": sum(timings.values())}
    (output / "pipeline.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary["timings_seconds"]))


if __name__ == "__main__":
    main()
